// AI туслахын системийн зааварт: бүх хуудасны жагсаалт
export function allPagesHelp(): string {
  return Object.entries(PAGES).map(([p, t]) => `«${LABELS[p] ?? p}» (${p}): ${t}`).join('\n')
}

export function pageHelp(pathname: string): string {
  const path = pathname.replace(/\/+$/, '') || '/'
  let best = ''
  for (const p of Object.keys(PAGES)) {
    // '/admin' (самбар) зөвхөн яг таарвал — эс бол тайлбаргүй дэд хуудас самбарын тайлбар авна
    const hit = path === p || (p !== '/admin' && path.startsWith(p + '/'))
    if (hit && p.length > best.length) best = p
  }
  return best ? PAGES[best] : 'Энэ хуудасны тайлбар одоохондоо алга. Цэснээс хэрэгтэй хуудсаа сонгоорой.'
}
